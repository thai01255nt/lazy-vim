# Two linked changes on one living capability (billing): feat-fee (B) changes BIL-R1 and edits settle; feat-receipt (A)
# names BIL-R1 in T-1 and locks settle. Order 1: A `after: feat-fee (strong)` → an order note pauses T-1 only; B
# archives first → A owes the reconcile (validate, archive, status); reconcile turns B's impact into notes in A (spec +
# recheck on the drifted locked symbol) and closes the order note; a re-run adds nothing. Order 2 (fresh copy): A
# `relates: feat-fee (low)` is understated; A archives first and B owns the reconcile.
