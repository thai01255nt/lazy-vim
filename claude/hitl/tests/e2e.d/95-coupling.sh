  printf '/**\n * Settles a charge.\n * @task T-1 @impl agent @status skeleton @prio 1\n */\nexport function settle(amount: number): number {\n  // TODO(impl): 1. settle\n  throw new Error("TODO(impl): settle");\n}\n' > src/settle.ts
  mkdir -p tests
  printf 'import { describe, it } from "node:test";\ndescribe("settle", () => {\n  /** @covers settle @ac T-1.AC1 @kind example @origin skeleton */\n  it.todo("T-1.AC1 receipt shows the settled amount");\n});\n' > tests/settle.test.ts
