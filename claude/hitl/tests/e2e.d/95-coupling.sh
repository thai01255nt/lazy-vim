sL1() {
  lk_project "$LK" "after: feat-fee (strong)"
  CLI coupling feat-receipt feat-fee --json > "$W/l1a.json"
  afile "$W/l1a.json" 'd.pairs[0].level === "strong" && d.pairs[0].evidence.some((e) => e.type === "ac-ref" && e.ref === "BIL-R1") && d.pairs[0].evidence.some((e) => e.type === "symbol") && d.links[0].rel === "after"'
  CLI spec validate --json > "$W/l1b.json" || { cat "$W/l1b.json"; return 1; }
  afile "$W/l1b.json" 'd.orderNotes.length === 1 && d.orderNotes[0].change === "feat-receipt" && d.orderNotes[0].note === "N-1"'
  contains .hitl/changes/feat-receipt/notes.md "- kind: order"
  CLI note list --change feat-receipt --json > "$W/l1c.json"
  afile "$W/l1c.json" 'd.changes[0].notes[0].blocks.join() === "T-1" && d.changes[0].notes[0].apply === "/hitl:plan feat-receipt reconcile feat-fee"'
  CLI status --json > "$W/l1d.json"
  afile "$W/l1d.json" 'd.changes.find((c) => c.id === "feat-receipt").links[0].paused.join() === "T-1" && d.tasks["T-2"].notes.length === 0 && d.tasks["T-1"].notes[0].waitFor === "feat-fee"'
  CLI approve T-1 --stage skeleton --by human --json > "$W/l1e.json" && { echo "T-1 is paused by the order note"; return 1; } || true
  afile "$W/l1e.json" 'd.ok === false && d.blockedBy[0].note === "N-1"'
  # the human resumes T-1 early for its skeleton (escape hatch), so settle is locked by feat-receipt
  CLI approve T-1 --stage skeleton --by human --ack N-1 --json > "$W/l1f.json"
  afile "$W/l1f.json" 'd.ok === true'
  afile "$LOCK" 'Object.values(d.symbols).some((s) => (s.task === "T-1" || (s.tasks || []).includes("T-1")))'
}
step LK1 "coupling: after: link → strong evidence, an order note pauses T-1 only (T-2 free); the human acks T-1's skeleton" sL1

sL2() {
  cd "$LK"
  # feat-fee edits settle (new signature) and archives first
  sed -i 's/export function settle(amount: number): number {/export function settle(amount: number, fee = 1): number {/' src/settle.ts
  CLI index > /dev/null
  CLI spec archive feat-fee --force > "$W/l2a.txt"
  contains "$W/l2a.txt" "🎯 next: /hitl:plan feat-receipt reconcile feat-fee"
  ls .hitl/archive/*-feat-fee/.prev.json > /dev/null
  CLI spec validate feat-receipt --json > "$W/l2b.json" || true
  afile "$W/l2b.json" 'd.items.some((i) => i.code === "RECONCILE_PENDING" && i.ref === "feat-fee")'
  CLI spec archive feat-receipt --dry-run --force --json > "$W/l2c.json" && { echo "archive must wait for the reconcile"; return 1; } || true
  afile "$W/l2c.json" 'd.ok === false && d.preconditions.reconcile.pending[0].from === "feat-fee"'
  CLI change feat-receipt --json > "$W/l2d.json"
  afile "$W/l2d.json" 'd.changes[0].reconcilePending[0].command === "/hitl:plan feat-receipt reconcile feat-fee"'
  CLI status --brief > "$W/l2e.txt"
  contains "$W/l2e.txt" "🔄 reconcile pending: feat-receipt from feat-fee"
}
step LK2 "coupling: feat-fee archives first → next line, .prev.json; feat-receipt owes the reconcile (validate, archive refused, change, brief)" sL2

sL3() {
  cd "$LK"
  cp .hitl/changes/feat-receipt/notes.md "$W/l3-notes-before.md"
  CLI reconcile feat-receipt --from feat-fee --dry-run --json > "$W/l3a.json"
  afile "$W/l3a.json" 'd.counts.new === 2 && d.findings[0].type === "spec" && d.findings[0].ref === "BIL-R1" && d.findings[0].diff.includes("+ - THEN the result is 11") && d.findings[1].type === "recheck" && d.closesOrder.join() === "N-1"'
  cmp -s .hitl/changes/feat-receipt/notes.md "$W/l3-notes-before.md" || { echo "dry run wrote notes.md"; return 1; }
  CLI reconcile feat-receipt --from feat-fee --json > "$W/l3b.json"
  afile "$W/l3b.json" 'd.added.join() === "N-2,N-3" && d.closed.join() === "N-1" && d.recorded'
  contains .hitl/changes/feat-receipt/notes.md "> Reconciled: feat-fee"
  contains .hitl/changes/feat-receipt/notes.md "- resolved: feat-fee archived; reconciled"
  contains .hitl/changes/feat-receipt/notes.md "- status: reopen pending"
  CLI reconcile feat-receipt --from feat-fee --json > "$W/l3c.json"
  afile "$W/l3c.json" 'd.counts.new === 0 && d.added.length === 0'
  CLI spec archive feat-receipt --dry-run --force --json > "$W/l3d.json" || true
  afile "$W/l3d.json" 'd.preconditions.reconcile.pending.length === 0 && d.preconditions.notes.open.map((n) => n.id).join() === "N-2,N-3"'
  [ ! -e .hitl/archive/*-feat-fee/notes.md ] || { echo "reconcile wrote into feat-fee"; return 1; }
}
step LK3 "coupling: reconcile dry run writes nothing; real run adds a spec note + a recheck (drifted settle), closes the order note; re-run adds nothing" sL3

sL4() {
  lk_project "$W/link-app2" "relates: feat-fee (low)"
  CLI spec validate --json > "$W/l4a.json" || true
  afile "$W/l4a.json" 'd.items.some((i) => i.code === "COUPLING_UNDERSTATED") && !d.orderNotes'
  CLI spec archive feat-receipt --force --json > "$W/l4b.json"
  afile "$W/l4b.json" 'd.ok && d.archive.reconcile[0].change === "feat-fee" && d.archive.reconcile[0].command === "/hitl:plan feat-fee reconcile feat-receipt"'
  CLI spec archive feat-fee --dry-run --force --json > "$W/l4c.json" && { echo "feat-fee must reconcile first"; return 1; } || true
  afile "$W/l4c.json" 'd.preconditions.reconcile.pending[0].from === "feat-receipt"'
  CLI status --json > "$W/l4d.json"
  afile "$W/l4d.json" 'd.next.command === "/hitl:plan feat-fee reconcile feat-receipt"'
  CLI reconcile feat-fee --from feat-receipt --json > "$W/l4e.json"
  afile "$W/l4e.json" 'd.recorded && d.fromArchived'
  CLI spec archive feat-fee --dry-run --force --json > "$W/l4f.json"
  afile "$W/l4f.json" 'd.ok && d.preconditions.reconcile.pending.length === 0'
}
step LK4 "coupling: relates (low) is understated; feat-receipt archives first → feat-fee owns the reconcile, then archives" sL4
