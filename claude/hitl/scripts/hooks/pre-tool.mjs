// Best effort, deny only when sure: in a hitl project, a shell segment that names a protected hitl path (isGenerated:
// index/ incl. the lock and sessions, living specs, archive, .base.json, notes.md, generated reviews, map files) AND
// writes it. Read-only use (cat, grep, jq, head, git diff|log|show) and hitl-index / node …hitl-index.mjs runs pass; a
