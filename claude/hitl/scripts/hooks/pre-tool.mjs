function applyEdit(old, ti, toolName) {
  if (toolName === "Write") return typeof ti.content === "string" ? ti.content : null;
  const edits = toolName === "MultiEdit" ? (Array.isArray(ti.edits) ? ti.edits : []) : [ti];
  let cur = old;
  for (const e of edits) {
    const from = e.old_string, to = e.new_string;
    if (typeof from !== "string" || typeof to !== "string") return null;
    if (from === "") { if (cur !== "") return null; cur = to; continue; }
    const at = cur.indexOf(from);
    if (at < 0) return null; // let the tool fail by itself
    cur = e.replace_all ? cur.split(from).join(to) : cur.slice(0, at) + to + cur.slice(at + from.length);
  }
  return cur;
}

const byOf = (seg) => { const m = /--by(?:=|\s+)["']?(human-override|human|auto)(?![\w-])/.exec(seg); return m ? m[1] : /--by\b/.test(seg) ? "?" : "human"; };
const stageOf = (seg) => {
  const m = /--stage(?:=|\s+)["']?(skeleton|tests|done|intent|accept|reopen|dismiss|defer)\b/.exec(seg) || /\bapprove\s+["']?T-\d+["']?\s+(skeleton|tests|done)\b/.exec(seg);
  return m ? m[1] : null;
};
/** Part of an approve segment after the `approve` word (the CLI's own arguments). */
const argsOf = (seg) => seg.replace(/^[\s\S]*?\bapprove\b/, "");
/** A change-form approve: `approve --change <id> --stage intent|accept|reopen|dismiss|defer` (either flag marks it). */
const isChangeSeg = (seg) => /--change\b/.test(argsOf(seg)) || /--stage(?:=|\s+)["']?(?:intent|accept|reopen|dismiss|defer)\b/.test(argsOf(seg));
const changeIdsOf = (seg) => [...argsOf(seg).matchAll(/--change(?:=|\s+)([^\s;&|]+)/g)].map((m) => m[1]);
const flagOf = (seg, f) => [...argsOf(seg).matchAll(new RegExp(`--${f}(?:=|\\s+)([^\\s;&|]+)`, "g"))].map((m) => m[1]);
const CHANGE_HUMAN = { accept: "Accept is human-only: type /hitl:approve <change-id> accept", reopen: "Reopen is human-only: type /hitl:approve <change-id> reopen [N-k]",
  dismiss: "Dismissing a note is human-only: type /hitl:approve <change-id> dismiss N-k <reason>", defer: "Deferring a note is human-only: type /hitl:approve <change-id> defer N-k <other-change>",
  intent: "Intent re-approval is human-only: type /hitl:approve <change-id> intent" };

/**
 * `--by human-override`: the user typed `/hitl:implement <T> --lane fast` (or `--feature <file> --lane fast`).
 * Multi-use within OVERRIDE_TTL_MS for the bound task(s), skeleton/tests stages only, main thread, plain single command.
 */
function overrideGate(root, input, R, cmd, seg) {
  const how = "type /hitl:implement <T> --lane fast";
  if (R !== "main") deny(`Fast-lane override is human-only: ${how}`);
  const tok = readSession(root, input.session_id).overrideToken;
  const fresh = tok && typeof tok.at === "number" && Date.now() - tok.at < OVERRIDE_TTL_MS && Date.now() >= tok.at - 1000;
  if (!fresh || !Array.isArray(tok.tasks)) deny(`Fast-lane override is human-only: ${how}`);
  if (CHAIN_RE.test(cmd)) deny("Run the approve command alone (no chaining, pipes or redirection)");
  const T = (/\bT-\d+\b/.exec(seg.replace(/^[\s\S]*?\bapprove\b/, "")) || [])[0];
  if (!T || !tok.tasks.includes(T)) deny(`Override token covers ${tok.feature ? `feature ${tok.feature} (${tok.tasks.join(", ")})` : tok.tasks.join(", ")}; ${how} for another task`);
  const stage = stageOf(seg);
  if (stage !== "skeleton" && stage !== "tests") deny("--by human-override needs an explicit --stage skeleton|tests (done stays a human /hitl:approve)");
  allow(`HITL fast-lane override for ${T} (${stage}) from the user's /hitl:implement --lane fast`);
}

async function approveGate(root, input, R, rawCmd) {
  const cmd = unquote(rawCmd);
  if (!APPROVE_RE.test(cmd)) {
    if (/hitl/.test(cmd) && INDIRECT_APPROVE_RE.test(cmd)) deny("Run hitl-index approve literally (no variables, eval or sh -c)");
    return;
  }
  // Judge every approve invocation separately, so `approve --by auto; approve --by human` cannot hide the human one.
  const segs = cmd.split(/[;&|\n\r`#]|\$\(/).filter((s) => APPROVE_RE.test(s));
  // the change-form stages (intent re-approval, accept of an archived change's drift) are human-only in every form:
  // no --by auto / human-override, not even as a dry run
  for (const s of segs) if (isChangeSeg(s) && byOf(s) !== "human") deny(`${CHANGE_HUMAN[stageOf(s)] || CHANGE_HUMAN.intent} (--by human only; never --by auto or human-override)`);
  // --ack releases a note's block for one task: only in a human approval, never --by auto / human-override
  for (const s of segs) if (/--ack\b/.test(argsOf(s)) && byOf(s) !== "human") deny("--ack is human-only: type /hitl:approve <T> <stage> --ack N-k (--by human only; never --by auto or human-override)");
  const human = segs.filter((s) => {
    if (byOf(s) === "auto") return false; // the CLI enforces low risk
    return !/--dry-run\b/.test(s); // preview only; does not consume the token
  });
  if (!human.length) return;
  if (human.length > 1) deny("One human approval per command: run each /hitl:approve separately");
  if (byOf(human[0]) === "human-override") overrideGate(root, input, R, cmd, human[0]);
  if (R !== "main") deny("Approval is human-only: type /hitl:approve <T>");
  const sid = input.session_id;
  const s = readSession(root, sid);
  const tok = s.approveToken;
  const fresh = tok && typeof tok.at === "number" && Date.now() - tok.at < TOKEN_TTL_MS && Date.now() >= tok.at - 1000;
  if (!fresh) deny("Approval is human-only: type /hitl:approve <T>");
  // The token is consumed here and the call is allowed outright, so a later permission check cannot swallow it.
  // Hence only a plain single command qualifies (checked before consuming; the token is kept on this deny).
  if (CHAIN_RE.test(cmd)) deny("Run the approve command alone (no chaining, pipes or redirection); the approval token is kept");
  // A token is bound to one task (`/hitl:approve T-n`), to one change and stage (`/hitl:approve <change-id> intent|accept`)
  // or, typed without a T-id, to any one task approve. A task token never authorizes --change and vice versa; an intent
  // token never authorizes accept and vice versa.
  const bind = approveBinding(tok.args);
  const seg = human[0];
  const cmdTask = /\bT-\d+\b/.exec(argsOf(seg));
  if (isChangeSeg(seg)) {
    const ids = changeIdsOf(seg);
    const want = stageOf(seg) || "intent";
    const exact = () => `hitl-index approve --change ${bind.change} --stage ${bind.stage}${bind.note ? ` --note ${bind.note}` : ""}${bind.to ? ` --to ${bind.to}` : ""}`
      + `${bind.stage === "dismiss" ? ' --reason "…"' : ""} --by human`;
    if (bind.kind !== "change") deny(`Approval token is ${bind.kind === "task" ? `for ${bind.task}` : "not bound to a change"}; type /hitl:approve <change-id> ${want} for a change-level ${want}`);
    if (ids.length !== 1 || ids[0] !== bind.change) deny(`Approval token is for change ${bind.change} (${bind.stage}); type /hitl:approve <change-id> ${want} for another change`);
    if (stageOf(seg) !== bind.stage) deny(`Approval token is for change ${bind.change} (${bind.stage}). Run exactly: ${exact()}`);
    if (cmdTask) deny(`A change approval names a change, not a task (${cmdTask[0]}): ${exact()}`);
    // a note decision is bound to the note (and defer to the target) the user typed; reopen to its note when one was typed
    const notes = flagOf(seg, "note");
    if (["dismiss", "defer"].includes(bind.stage) && (!bind.note || notes.length !== 1 || notes[0] !== bind.note))
      deny(`Approval token is for ${bind.change} ${bind.stage} ${bind.note || "(no note id typed)"}; the user types /hitl:approve ${bind.change} ${bind.stage} N-k …. Run exactly: ${exact()}`);
    if (bind.stage === "reopen" && (notes.length > 1 || (notes.length && notes[0] !== bind.note)))
      deny(`Approval token is for ${bind.change} reopen${bind.note ? ` ${bind.note}` : " (all pending rechecks)"}. Run exactly: ${exact()}`);
    if (bind.stage === "defer" && (flagOf(seg, "to").length !== 1 || flagOf(seg, "to")[0] !== bind.to)) deny(`Approval token defers ${bind.note} to ${bind.to || "(no target typed)"}. Run exactly: ${exact()}`);
  } else {
    if (bind.kind === "change") deny(`Approval token is for change ${bind.change} (${bind.stage}); type /hitl:approve <T> for a task approval`);
    if (bind.kind === "task" && (!cmdTask || cmdTask[0] !== bind.task)) deny(`Approval token is for ${bind.task}; type /hitl:approve <T> for another task`);
  }
  // every acked note id must be one the user typed in this /hitl:approve
  const ackIds = [...argsOf(seg).matchAll(/--ack(?:=|\s+)([^\s;&|]+)/g)].flatMap((m) => m[1].split(",")).filter(Boolean);
  if (ackIds.length) {
    const typed = new Set(String(tok.args || "").match(/\bN-\d+\b/g) || []);
    const extra = ackIds.filter((i) => !typed.has(i));
    if (extra.length) deny(`--ack ${extra.join(",")} was not typed by the user; the user types /hitl:approve <T> <stage> --ack ${extra.join(",")}. The approval token is kept`);
  }
  await updateSession(root, sid, (x) => { x.approveToken = null; return x; });
  allow(`HITL approve token for this /hitl:approve${bind.kind === "change" ? ` ${bind.change} ${bind.stage}` : ""} (one use)`);
}

async function main(input) {
  const tool = input.tool_name;
  if (!tool) silent();
  const R = role(input);
  const cmd = tool === "Bash" ? String((input.tool_input || {}).command || "") : "";

  // 0. Bash writes to protected hitl files (every role; cheap: only commands naming .hitl are parsed)
  if (tool === "Bash") bashGuard(cmd, input.cwd || process.cwd());

  // Fast path (no module loading): main-thread reads, and Bash without approve.
  if (R === "main" && READ_TOOLS.has(tool)) silent();
  if (R === "main" && tool === "Bash" && !/\bapprove\b/.test(cmd)) silent();
  if (R === "other" && (READ_TOOLS.has(tool) || (tool === "Bash" && !/\bapprove\b/.test(cmd)))) silent();
  if (!EDIT_TOOLS.has(tool) && !READ_TOOLS.has(tool) && tool !== "Bash") silent();

  const abs = toolPath(input);
  const cwd = input.cwd || process.cwd();
  const root = findRootSync(abs ? path.dirname(abs) : cwd) || (abs ? findRootSync(cwd) : null);
  if (!root) silent();
  const rel = relPath(root, abs);

  // 1. Generated files
  if (EDIT_TOOLS.has(tool) && rel) {
    if (isGenerated(rel)) deny(generatedReason(rel));
    if (rel === CONFIG_REL && R !== "main") deny("Generated by hitl-index; use the CLI (see /hitl:sync)");
  }

  // 5. Approve token (checked for every role so subagents cannot self-approve)
  if (tool === "Bash") await approveGate(root, input, R, cmd);

  const a = await api();
  const config = await a.loadConfig(root);

  // 2. test-author isolation
  if (R === "test-author") {
    if (tool === "Read") { if (!testAuthorMayRead(rel, a, config)) deny("test-author sees only the contract pack"); }
    else if (tool === "Grep") {
      const p = (input.tool_input || {}).path;
      if (!p) deny(`test-author sees only the contract pack: Grep needs a path inside tests or ${CUSTOM}{${TEST_AUTHOR_DIRS.join(",")}}`);
      let isDir = false;
      try { isDir = fs.statSync(abs).isDirectory(); } catch {}
      const ok = isDir ? testAuthorMayGrepDir(rel, a, config) : testAuthorMayRead(rel, a, config);
      if (!ok) deny("test-author sees only the contract pack");
    } else if (tool === "Glob") { /* names only */ }
    else if (EDIT_TOOLS.has(tool)) { if (!(rel && a.isTestFile(rel, config))) deny("test-author writes only test files"); }
    else if (tool === "Bash") { if (!safeBash(cmd, TEST_AUTHOR_BASH)) deny("test-author may run only: hitl-index test|context|status (no chaining or redirection)"); }
  }

  // 3. reviewer / finding-verifier: read-only except reviews/
  if (R === "reviewer" || R === "finding-verifier") {
    if (EDIT_TOOLS.has(tool) && !(rel && rel.startsWith(CUSTOM + "reviews/"))) deny(`${R} may write only under ${CUSTOM}reviews/`);
    if (tool === "Bash" && !safeBash(cmd, REVIEWER_BASH)) deny(`${R} may run only: hitl-index context|status|drift|test, git diff|log|show|blame (no chaining or redirection)`);
  }

  // 4. codebase-mapper: only docs/*.md except CODEBASE-MAP.md
  if (R === "codebase-mapper" && EDIT_TOOLS.has(tool)) {
    const ok = rel && MAPPER_DOC_RE.test(rel) && rel !== CUSTOM + "docs/CODEBASE-MAP.md";
    if (!ok) deny(`codebase-mapper may write only ${CUSTOM}docs/*.md (not CODEBASE-MAP.md)`);
  }

  // 4b. spec-scout / spec-reviewer: write only their scratch file in a change folder; read-only CLI; the reviewer reads
  // only .hitl/ (and files outside the project, e.g. plugin docs) — it judges the spec, never the code
  if (SPEC_AGENT[R]) {
    const S = SPEC_AGENT[R];
    if (EDIT_TOOLS.has(tool)) {
      const ok = rel && new RegExp(`^${HITL_RE}changes/[^/]+/${S.file.replace(/\./g, "\\.")}$`).test(rel);
      if (!ok) deny(`${R} may write only ${CUSTOM}changes/<id>/${S.file}`);
    }
    if (tool === "Bash" && !safeBash(cmd, S.bash)) deny(`${R} may run only: ${S.allowed} (no chaining or redirection)`);
    if (R === "spec-reviewer" && tool === "Grep" && !(input.tool_input || {}).path) deny(`spec-reviewer reads only ${CUSTOM}: Grep needs a path inside it`);
    if (R === "spec-reviewer" && (tool === "Read" || tool === "Grep") && rel !== null && !(rel === CUSTOM.slice(0, -1) || rel.startsWith(CUSTOM)))
      deny(`spec-reviewer reads only ${CUSTOM} (the spec, not the code)`);
  }

  // 4c. work-router: decides the route of new work for /hitl:go; writes only its verdict, runs only read-only CLI
  if (R === "work-router") {
    if (EDIT_TOOLS.has(tool) && rel !== CUSTOM + ".inbox/route.json") deny(`work-router may write only ${CUSTOM}.inbox/route.json`);
    if (tool === "Bash" && (!safeBash(cmd, WORK_ROUTER_BASH) || WORK_ROUTER_WRITES.test(cmd)))
      deny("work-router may run only: hitl-index change, status, context, spec list|show (no --sync-tags, --out, chaining or redirection)");
  }

  // 6. Edit simulation
  if (!(tool === "Edit" || tool === "Write" || tool === "MultiEdit") || !rel) silent();
  const isTest = a.isTestFile(rel, config);
  if (R === "implementer" && isTest) deny("implementer never edits tests; report the problem instead");
  if (!a.langOf(rel, config)) silent();

  let oldText = "";
  try { oldText = fs.readFileSync(abs, "utf8"); } catch { oldText = ""; }
  const newText = applyEdit(oldText, input.tool_input || {}, tool);
  if (newText === null || newText === oldText) silent();

  const lock = await a.readJson(a.paths(root).lock, {});
  const lsyms = (lock && lock.symbols) || {};
  const ltests = (lock && lock.tests) || {};
  if (!Object.keys(lsyms).length && !Object.keys(ltests).length) silent();

  let before, after;
  try {
    [before] = await a.parseSources(root, [{ path: rel, content: oldText }], config);
    [after] = await a.parseSources(root, [{ path: rel, content: newText }], config);
  } catch { silent(); }
  if (!before || !after || after.parseError) silent(); // PostToolUse reports PARSE_ERROR
  const afterById = new Map((after.symbols || []).map((s) => [s.id, s]));

  for (const S of before.symbols || []) {
    const N = afterById.get(S.id);
    const ref = S.name || shortName(S.id);
    const changed = !N || N.sigHash !== S.sigHash || N.intentHash !== S.intentHash || N.bodyHash !== S.bodyHash;
    if (S.tags && S.tags.impl === "manual" && lsyms[S.id] && changed) {
      deny(`${ref} is @impl manual (human-owned). Ask the user to edit it, or the user flips @impl to agent.`);
    }
    if (S.kind === "test" && ltests[S.id] && R !== "test-author" && (!N || N.bodyHash !== S.bodyHash || N.intentHash !== S.intentHash)) {
      deny(`Locked test ${ref}; tests change only via /hitl:test + /hitl:approve <T> tests`);
    }
    if (R === "implementer" && lsyms[S.id] && (!N || N.sigHash !== S.sigHash || N.intentHash !== S.intentHash || tagsKey(N.tags) !== tagsKey(S.tags))) {
      deny(`Locked contract ${ref}: signature, docstring and @tags are frozen; report contractIssue instead`);
    }
  }
  // 0.12: the implementer never builds a task of a change that waits for another change (a note with `source:`)
  if (R === "implementer") {
    const owners = new Set();
    for (const S of before.symbols || []) {
      const N = afterById.get(S.id);
      if (lsyms[S.id] && (!N || N.bodyHash !== S.bodyHash)) for (const T of [...(lsyms[S.id].tasks || []), lsyms[S.id].task].filter(Boolean)) owners.add(T);
    }
    const why = await changeWaitOf(root, lock, [...owners]);
    if (why) deny(why);
  }
  // R = main with sig/intent change on a locked symbol → allowed (PostToolUse warns)
  silent();
}

/** First wait reason of the (active) changes owning tasks Ts, or null. Best effort: any error → null. */
async function changeWaitOf(root, lock, Ts) {
  if (!Ts.length) return null;
  try {
    const [tm, nm] = await Promise.all([optionalLib("tasksmd.mjs"), optionalLib("notes.mjs")]);
    if (!tm || !nm) return null;
    const seen = new Set();
    for (const T of Ts) {
      const loc = tm.changeOfFile(lock?.tasks?.[T]?.file || "");
      if (!loc.change || loc.archived || seen.has(loc.change)) continue;
      seen.add(loc.change);
      const w = nm.changeWait(await nm.readNotes(root, loc.dir));
      if (w.blocked) return `${T} belongs to ${loc.change}, which is blocked: ${nm.waitReasons(loc.change, w)[0]}`;
    }
  } catch { return null; }
  return null;
}

run(main, { watchdogMs: 18000 });
