const HITL_PATH_RE = /[^\s'"`<>|;&()=]*\.hitl(?:\/[^\s'"`<>|;&()]*)?/g;
/** Project-relative `.hitl/…` part of a path token, or null. */
const hitlRel = (tok) => { const i = tok.indexOf(".hitl"); if (i < 0) return null; const r = tok.slice(i).replace(/\/+$/, ""); return r === ".hitl" || r.startsWith(".hitl/") ? r : null; };
/** A protected file, or a directory whose contents are protected (`.hitl/index`, `.hitl/specs`, an archived change). */
const protectedRel = (rel) => !!rel && (isGenerated(rel) || (rel !== ".hitl" && isGenerated(rel + "/_")));
const protTok = (tok) => { const r = hitlRel(String(tok || "").replace(/^\w+=/, "")); return protectedRel(r) ? r : null; };
const HEREDOC_RE = /<<-?\s*(['"]?)([A-Za-z_][\w-]*)\1/;
/** Lines of a command split into shell text and heredoc bodies: {shell, docs:[{line, body}]} (line = the opening line). */
function splitHeredocs(cmd) {
  const lines = cmd.split(/\r?\n/), shell = [], docs = [];
  for (let i = 0; i < lines.length; i++) {
    shell.push(lines[i]);
    const m = HEREDOC_RE.exec(lines[i]);
    if (!m) continue;
    const body = [];
    for (i++; i < lines.length && lines[i].replace(/^\t+/, "") !== m[2]; i++) body.push(lines[i]);
    docs.push({ line: lines[shell.length - 1], body: body.join("\n") });
  }
  return { shell: shell.join("\n"), docs };
}
/** Split shell text on unquoted ; && || | & and newlines (keeps `2>&1`, `&>` inside a segment). */
function shellSegments(cmd) {
  const out = []; let cur = "", q = null;
  for (let i = 0; i < cmd.length; i++) {
    const c = cmd[i];
    if (q) { cur += c; if (c === q) q = null; else if (c === "\\" && q === '"') cur += cmd[++i] ?? ""; continue; }
    if (c === "'" || c === '"') { q = c; cur += c; continue; }
    if (c === "\\") { cur += c + (cmd[++i] ?? ""); continue; }
    const amp = c === "&" && cmd[i - 1] !== ">" && cmd[i + 1] !== ">";
    if (c === ";" || c === "\n" || c === "\r" || c === "|" || amp) { out.push(cur); cur = ""; if ((c === "|" || c === "&") && cmd[i + 1] === c) i++; continue; }
    cur += c;
  }
  out.push(cur);
  return out.map((x) => x.trim()).filter(Boolean);
}
/** Whitespace tokens of a segment, quotes removed. */
const words = (seg) => (seg.match(/(?:[^\s'"]+|'[^']*'|"(?:\\.|[^"\\])*")+/g) || []).map((w) => w.replace(/['"]/g, ""));
const REDIRECT_RE = /(?:\d|&)?>>?\|?\s*([^\s;&|<>()]+)/g;
const HITL_CLI_RE = /^(?:\S*\/)?hitl-index(?:\.mjs)?$/;
const INTERP_RE = /^(?:\S*\/)?(?:python[\d.]*|node|nodejs|ruby|perl|deno|bun)$/;
const SHELL_RE = /^(?:\S*\/)?(?:ba|z|da|k)?sh$/;
const PREFIX_WORDS = new Set(["sudo", "command", "env", "nice", "nohup", "time", "exec", "builtin"]);
const WRITE_API_RE = new RegExp([
  String.raw`\bopen\s*\([^)]*?,\s*(?:mode\s*=\s*)?[rbt]*["'][^"']*[wax+]`, String.raw`\.write_(?:text|bytes)\s*\(`,
  String.raw`\b(?:writeFileSync|appendFileSync|writeFile|appendFile|createWriteStream|unlinkSync|rmSync|renameSync|copyFileSync|truncateSync|cpSync)\s*\(`,
  String.raw`\bos\.(?:remove|unlink|rename|replace|truncate)\s*\(`, String.raw`\bshutil\.(?:copy\w*|move|rmtree)\s*\(`, String.raw`\.unlink\s*\(`,
  String.raw`\bFile\.(?:write|delete|rename)\b`,
].join("|"));
/** Inline code that names a protected path and calls a write API: the path, or null. */
const codeWrite = (code) => (WRITE_API_RE.test(code) ? (code.match(HITL_PATH_RE) || []).map(protTok).find(Boolean) || null : null);
/** The command word of a segment (after env assignments and sudo/env/…) and its arguments. */
function commandOf(seg) {
  const w = words(seg.replace(REDIRECT_RE, " "));
  let i = 0;
  while (i < w.length && (/^\w+=/.test(w[i]) || PREFIX_WORDS.has(w[i]))) i++;
  return { word: w[i] || "", name: (w[i] || "").replace(/^\S*\//, ""), args: w.slice(i + 1) };
}

/**
 * The first protected path a Bash command writes, as {rel, op}, or null. Per segment: redirects (> >> &> 2> >|), tee,
 * sed/perl/awk in place, cp/install/rsync/ln/dd targets, mv (either side), rm/unlink/truncate/shred/rmdir,
 * git checkout|restore|rm|mv; inline python/node/ruby/perl code (-c/-e/-p or a heredoc) that names a protected path and
 * calls a write API; a heredoc fed to sh/bash is judged as shell.
 */
function bashProtectedWrite(cmd, depth = 0) {
  if (typeof cmd !== "string" || !cmd.includes(".hitl") || depth > 2) return null;
  const { shell, docs } = splitHeredocs(cmd);
  for (const d of docs) {
    const c = commandOf(shellSegments(d.line).find((s) => HEREDOC_RE.test(s)) || d.line);
    if (SHELL_RE.test(c.word)) { const r = bashProtectedWrite(d.body, depth + 1); if (r) return r; }
    else if (INTERP_RE.test(c.word) && !c.args.some((a) => /hitl-index\.mjs$/.test(a))) { const r = codeWrite(d.body); if (r) return { rel: r, op: "inline script" }; }
  }
  for (const seg of shellSegments(shell)) {
    // redirects first: a write whatever the command (hitl-index included)
    for (const m of seg.replace(HEREDOC_RE, " ").matchAll(REDIRECT_RE)) {
      const t = m[1].replace(/['"]/g, "");
      if (t.startsWith("&")) continue;
      const r = protTok(t); if (r) return { rel: r, op: "redirect" };
    }
    const { word, name, args } = commandOf(seg.replace(HEREDOC_RE, " "));
    if (!name || HITL_CLI_RE.test(word)) continue;
    if (INTERP_RE.test(word) && args.some((a) => /hitl-index\.mjs$/.test(a))) continue;
    const opts = args.filter((a) => a.startsWith("-")), files = args.filter((a) => !a.startsWith("-"));
    const any = (list) => list.map(protTok).find(Boolean) || null;
    let r = null, op = name;
    if (name === "tee") r = any(files);
    else if (name === "sed" || name === "gsed") { if (opts.some((o) => /^-[a-zA-Z]*i|^--in-place/.test(o))) { r = any(files); op = "sed -i"; } }
    else if (name === "perl" && opts.some((o) => /^-[a-zA-Z]*i/.test(o))) { r = any(files); op = "perl -i"; }
    else if (name === "awk" || name === "gawk") { if (args.join(" ").includes("-i inplace")) { r = any(files); op = "awk -i inplace"; } }
    else if (["cp", "install", "rsync", "ln"].includes(name)) r = opts.some((o) => o === "-t" || o.startsWith("--target-directory")) ? any(files) : protTok(files.at(-1));
    else if (["mv", "rm", "unlink", "truncate", "shred", "rmdir"].includes(name)) r = any(files);
    else if (name === "dd") r = any(args.filter((a) => a.startsWith("of=")).map((a) => a.slice(3)));
    else if (name === "git" && ["checkout", "restore", "rm", "mv"].includes(files[0])) { r = any(files.slice(1)); op = `git ${files[0]}`; }
    else if (INTERP_RE.test(word) && opts.some((o) => /^-[a-zA-Z]*[ceEp]$/.test(o) || o === "--eval" || o === "--print")) { r = codeWrite(seg); op = "inline script"; }
    if (r) return { rel: r, op };
  }
  return null;
}
function bashGuard(cmd, cwd) {
  const hit = bashProtectedWrite(cmd);
  if (!hit) return;
  // only in a hitl project: the cwd's, or the one an absolute protected path lives in
  const abs = (cmd.match(HITL_PATH_RE) || []).find((t) => t.startsWith("/") && protTok(t));
  if (!findRootSync(cwd) && !(abs && findRootSync(abs.slice(0, abs.indexOf(".hitl")) || "/"))) return;
  deny(`Bash would write ${hit.rel} (${hit.op}). ${generatedReason(hit.rel)}. Reading it (cat, grep, jq, head, git diff) is fine; use the hitl-index command instead of writing it from the shell`);
}

