// Merge of a change's spec deltas into the living specs (design v3 §7). Pure: callers pass parsed docs and get back
// the planned result plus the full new text of every living file to write. IO (atomic write, folder move) is in
// lib/changes.mjs + cmd/spec.mjs.
import { KIND_ORDER, KINDS, allocate, compareIds, formatId, parseId, rewriteIds } from "./specids.mjs";
import { LIVING_HEADER, blockHash, normalizeBlock, usedIds } from "./specmd.mjs";
import { HITL_PREFIX } from "./paths.mjs";

export const SPECS_REL = `${HITL_PREFIX}specs`;
export const specRel = (cap) => `${SPECS_REL}/${cap}/spec.md`;
export const GLOSSARY_REL = `${SPECS_REL}/GLOSSARY.md`;
export const GLOSSARY_HEADER = "<!-- audience: business · generated by hitl-index spec merge — edit through a change, not by hand -->";

const same = (a, b) => normalizeBlock(a) === normalizeBlock(b);

// ---------------------------------------------------------------- living model + render
/** Living spec doc -> mutable model. */
export function livingModel(doc) {
  return {
    title: doc.title, capability: doc.capability, key: doc.key, updated: doc.updated, purpose: doc.purpose,
    blocks: doc.blocks.map((b) => ({ kind: b.kind, id: b.id, title: b.title, text: b.livingText, scenarios: b.scenarios.map((s) => ({ id: s.id, title: s.title })) })),
    retired: doc.retired.map((r) => ({ id: r.id, raw: r.raw })),
    history: [...doc.history],
  };
}

/** Render a living spec model (canonical section order: Purpose, Requirements, Rules, Flows, Retired IDs, Change History). */
export function renderLiving(m) {
  const out = [LIVING_HEADER, `# ${m.title}`, `> capability: ${m.capability} | key: ${m.key}${m.updated ? ` | updated: ${m.updated}` : ""}`, ""];
  if (m.purpose) out.push("## Purpose", m.purpose, "");
  for (const kind of KIND_ORDER) {
    const bs = m.blocks.filter((b) => b.kind === kind);
    if (!bs.length && kind !== "requirement") continue;
    out.push(`## ${KINDS[kind].section}`, "");
    for (const b of bs) out.push(b.text, "");
  }
  if (m.retired.length) out.push("## Retired IDs", ...m.retired.map((r) => r.raw), "");
  if (m.history.length) out.push("## Change History", ...m.history, "");
  return out.join("\n").replace(/\n{3,}/g, "\n\n").replace(/\n+$/, "\n");
}

export function renderGlossary(m) {
  const out = [GLOSSARY_HEADER, `# ${m.title || "Glossary"}`, `> updated: ${m.updated}`, ""];
  for (const t of [...m.terms].sort((a, b) => a.key.localeCompare(b.key))) out.push(t.text, "");
  return out.join("\n").replace(/\n{3,}/g, "\n\n").replace(/\n+$/, "\n");
}

// ---------------------------------------------------------------- planning one capability
/**
 * planCapability({living, delta, change, date, base, acceptBase, renumber, reserved, retire}) -> result.
 *  living: parsed living doc or null (new capability); delta: parsed delta doc; base: {ID: "sha256:…"};
 *  reserved: {R:Set,BR:Set,UC:Set} numbers used by OTHER active changes (avoided on renumber).
 * Result: {capability, key, created, deleted, added[], modified[], removed[], alreadyApplied[], renumbered{}, conflicts[], warnings[], model, changed}
 */
export function planCapability({ living, delta, change, date, base = {}, acceptBase = [], renumber = false, reserved = null, retire = false }) {
  const cap = delta.capability;
  const res = { capability: cap, key: living?.key || delta.key, created: !living, deleted: false, added: [], modified: [], removed: [],
    alreadyApplied: [], renumbered: {}, conflicts: [], warnings: [], model: null, changed: false };
  const conflict = (code, ref, message) => res.conflicts.push({ code, ref, capability: cap, message });
  const accept = new Set(acceptBase);
  if (living && delta.key && living.key && living.key !== delta.key) conflict("CAP_KEY_CHANGED", delta.key, `${cap}: delta key ${delta.key} ≠ living key ${living.key} (keys never change)`);
  if (!living) {
    for (const b of delta.blocks) if (b.op !== "ADDED") conflict("DELTA_NEW_CAP_NOT_ADDED_ONLY", b.id, `${cap} is a new capability: only ADDED blocks are allowed (${b.op} ${b.id})`);
    if (!delta.purpose) conflict("PURPOSE_MISSING", cap, `${cap} is a new capability: the delta needs a ## Purpose`);
  }
  const m = living ? livingModel(living) : { title: delta.title || cap, capability: cap, key: delta.key, updated: null, purpose: delta.purpose, blocks: [], retired: [], history: [] };
  const byId = new Map(m.blocks.map((b) => [b.id, b]));
  const retired = new Set(m.retired.map((r) => r.id));
  // ids in use for renumbering: living + retired + this delta + other active changes
  const used = usedIds(living || { blocks: [], retired: [] });
  usedIds(delta, used);
  for (const k of ["R", "BR", "UC"]) for (const n of reserved?.[k] || []) used[k].add(n);
  const baseCheck = (id, cur) => {
    if (!base[id] || accept.has(id)) return;
    if (base[id] !== blockHash(cur.text)) conflict("BASE_CHANGED", id, `${id} changed in the living spec since this change was written (base hash differs); update the delta or --accept-base ${id}`);
  };
  const ops = { REMOVED: [], MODIFIED: [], ADDED: [] };
  for (const kind of KIND_ORDER) for (const op of ["REMOVED", "MODIFIED", "ADDED"]) for (const b of delta.blocks) if (b.kind === kind && b.op === op && (living || op === "ADDED")) ops[op].push(b);

  const plan = [];
  for (const b of ops.REMOVED) {
    const cur = byId.get(b.id);
    if (cur) { baseCheck(b.id, cur); plan.push({ op: "REMOVED", b, cur }); }
    else if (retired.has(b.id)) res.alreadyApplied.push(b.id);
    else conflict("DELTA_TARGET_MISSING", b.id, `REMOVED ${b.id} is not in the living spec`);
  }
  for (const b of ops.MODIFIED) {
    const cur = byId.get(b.id);
    if (!cur) { conflict("DELTA_TARGET_MISSING", b.id, `MODIFIED ${b.id} is not in the living spec${retired.has(b.id) ? " (it is retired)" : ""}`); continue; }
    if (same(cur.text, b.livingText)) { res.alreadyApplied.push(b.id); continue; }
    baseCheck(b.id, cur);
    const oldS = new Map(cur.scenarios.map((s) => [s.id, s]));
    for (const s of b.scenarios) {
      if (oldS.has(s.id) && oldS.get(s.id).title !== s.title) res.warnings.push({ code: "SCN_RETITLED", ref: s.id, capability: cap, message: `${s.id} title changed ("${oldS.get(s.id).title}" → "${s.title}"): was the id reused for a different example?` });
      if (!oldS.has(s.id) && retired.has(s.id)) conflict("DELTA_ID_TAKEN", s.id, `${s.id} is retired and cannot be reused`);
    }
    plan.push({ op: "MODIFIED", b, cur });
  }
  const renum = {};
  for (const b of ops.ADDED) {
    const cur = byId.get(b.id);
    let taken = null;
    if (cur) { if (same(cur.text, b.livingText)) { res.alreadyApplied.push(b.id); continue; } taken = "living"; }
    else if (retired.has(b.id)) taken = "retired";
    if (taken && !renumber) { conflict("DELTA_ID_TAKEN", b.id, `ADDED ${b.id} is already ${taken}${taken === "living" ? " with different text" : ""} (another change took it; use --renumber)`); continue; }
    let text = b.livingText; let id = b.id; let scenarios = b.scenarios.map((s) => ({ id: s.id, title: s.title }));
    if (taken) {
      const p = parseId(b.id);
      const [n] = allocate(used[p.kind], 1); used[p.kind].add(n);
      id = formatId(p.key, p.kind, n);
      renum[b.id] = id;
    }
    plan.push({ op: "ADDED", b, id, text, scenarios });
  }
  if (Object.keys(renum).length) {
    res.renumbered = renum;
    for (const p of plan) if (p.op === "ADDED") {
      p.id = renum[p.b.id] ?? p.id;
      p.text = rewriteIds(p.text, renum);
      p.scenarios = p.scenarios.map((s) => ({ id: rewriteIds(s.id, renum), title: s.title }));
    }
  }
  if (res.conflicts.length) return res;

  // apply in memory: REMOVED → MODIFIED → ADDED (per kind order already)
  for (const p of plan) {
    if (p.op === "REMOVED") {
      m.blocks.splice(m.blocks.indexOf(p.cur), 1);
      m.retired.push({ id: p.b.id, raw: `- ${p.b.id} ${p.cur.title} — removed by ${change} (${date}): ${p.b.reason}` });
      for (const s of p.cur.scenarios) retired.add(s.id);
      res.removed.push(p.b.id);
    } else if (p.op === "MODIFIED") {
      const nb = { kind: p.b.kind, id: p.b.id, title: p.b.title, text: p.b.livingText, scenarios: p.b.scenarios.map((s) => ({ id: s.id, title: s.title })) };
      const keep = new Set(nb.scenarios.map((s) => s.id));
      for (const s of p.cur.scenarios) if (!keep.has(s.id) && !retired.has(s.id)) {
        m.retired.push({ id: s.id, raw: `- ${s.id} ${s.title} — removed by ${change} (${date}): dropped from ${p.b.id}` });
        retired.add(s.id);
      }
      m.blocks[m.blocks.indexOf(p.cur)] = nb;
      res.modified.push(p.b.id);
    }
  }
  const adds = plan.filter((p) => p.op === "ADDED").sort((a, b) => compareIds(a.id, b.id));
  for (const p of adds) { m.blocks.push({ kind: p.b.kind, id: p.id, title: p.b.title, text: p.text, scenarios: p.scenarios }); res.added.push(p.id); }
  // migrated tombstones
  for (const r of delta.retired || []) if (!retired.has(r.id)) { m.retired.push({ id: r.id, raw: r.raw }); retired.add(r.id); res.changed = true; }
  if (living && delta.purpose && normalizeBlock(delta.purpose) !== normalizeBlock(m.purpose || "")) { m.purpose = delta.purpose; res.changed = true; }
  const applied = res.added.length + res.modified.length + res.removed.length;
  if (applied || res.changed || !living) {
    res.changed = true;
    const parts = [...res.added.map((x) => `+${x}`), ...res.modified.map((x) => `~${x}`), ...res.removed.map((x) => `-${x}`)];
    const notes = plan.filter((p) => p.op === "MODIFIED" && p.b.changed).map((p) => `${p.b.id}: ${p.b.changed}`);
    m.history.push(`- ${date} ${change}: ${parts.join(" ") || "(purpose)"}${notes.length ? ` — ${notes.join("; ")}` : ""}`);
    m.updated = date;
  }
  if (!m.blocks.length) {
    if (retire) res.deleted = true;
    else conflict("CAP_EMPTY", cap, `${cap} would have no requirements, rules or flows left; mark it "retired" in the proposal ## Capabilities to delete it`);
  }
  res.model = m;
  return res;
}

// ---------------------------------------------------------------- glossary
/** planGlossary({living, delta, date}) -> {added, modified, removed, alreadyApplied, conflicts, model, changed}. */
export function planGlossary({ living, delta, date }) {
  const res = { added: [], modified: [], removed: [], alreadyApplied: [], conflicts: [], model: null, changed: false };
  const m = { title: living?.title || "Glossary", updated: living?.updated || date, terms: (living?.terms || []).map((t) => ({ key: t.key, term: t.term, text: t.text })) };
  const idx = () => new Map(m.terms.map((t, i) => [t.key, i]));
  for (const op of ["REMOVED", "MODIFIED", "ADDED"]) for (const t of delta?.terms || []) {
    if (t.op !== op) continue;
    const i = idx().get(t.key);
    if (op === "REMOVED") { if (i === undefined) res.alreadyApplied.push(t.term); else { m.terms.splice(i, 1); res.removed.push(t.term); } }
    else if (op === "MODIFIED") {
      if (i === undefined) res.conflicts.push({ code: "DELTA_TARGET_MISSING", ref: t.term, capability: null, message: `MODIFIED term "${t.term}" is not in GLOSSARY.md` });
      else if (same(m.terms[i].text, t.text)) res.alreadyApplied.push(t.term);
      else { m.terms[i] = { key: t.key, term: t.term, text: t.text }; res.modified.push(t.term); }
    } else if (i !== undefined) {
      if (same(m.terms[i].text, t.text)) res.alreadyApplied.push(t.term);
      else res.conflicts.push({ code: "DELTA_ID_TAKEN", ref: t.term, capability: null, message: `ADDED term "${t.term}" already exists in GLOSSARY.md with a different text (use MODIFIED)` });
    } else { m.terms.push({ key: t.key, term: t.term, text: t.text }); res.added.push(t.term); }
  }
  if (res.added.length + res.modified.length + res.removed.length) { res.changed = true; m.updated = date; }
  res.model = m;
  return res;
}

// ---------------------------------------------------------------- whole change
/**
 * mergeChange({changeId, deltas, glossaryDelta, proposal, living, glossary, base, acceptBase, renumber, reserved, date, withGlossary})
 *  living: Map cap -> {doc, text} (current files); glossary: {doc, text} | null; reserved: Map cap -> {R,BR,UC sets}.
 * -> {capabilities[], glossary, conflicts[], warnings[], writes:[{file, text|null}], renumbered{}, base}
 */
export function mergeChange({ changeId, deltas, glossaryDelta = null, proposal = null, living, glossary = null, base = {}, acceptBase = [],
  renumber = false, reserved = new Map(), date, withGlossary = true }) {
  const out = { capabilities: [], glossary: { added: [], modified: [], removed: [] }, conflicts: [], warnings: [], writes: [], renumbered: {}, base: { ...base } };
  const retiredCaps = new Set((proposal?.capabilities || []).filter((c) => c.change === "retired").map((c) => c.capability));
  // capability keys must stay unique across living specs
  const keyOwner = new Map([...living.values()].map((l) => [l.doc.key, l.doc.capability]));
  for (const d of [...deltas].sort((a, b) => a.capability.localeCompare(b.capability))) {
    const cur = living.get(d.capability) || null;
    if (!cur && d.key && keyOwner.has(d.key) && keyOwner.get(d.key) !== d.capability)
      out.conflicts.push({ code: "CAP_KEY_DUP", ref: d.key, capability: d.capability, message: `key ${d.key} already belongs to ${keyOwner.get(d.key)}` });
    const r = planCapability({ living: cur?.doc || null, delta: d, change: changeId, date, base, acceptBase, renumber, reserved: reserved.get(d.capability), retire: retiredCaps.has(d.capability) });
    out.conflicts.push(...r.conflicts); out.warnings.push(...r.warnings);
    Object.assign(out.renumbered, r.renumbered);
    out.capabilities.push({ capability: r.capability, file: specRel(r.capability), created: r.created, deleted: r.deleted, added: r.added, modified: r.modified,
      removed: r.removed, alreadyApplied: r.alreadyApplied, renumbered: r.renumbered, _model: r.model, _changed: r.changed, _cur: cur });
  }
  if (withGlossary && glossaryDelta?.terms?.length) {
    const g = planGlossary({ living: glossary?.doc || null, delta: glossaryDelta, date });
    out.conflicts.push(...g.conflicts);
    out.glossary = { added: g.added, modified: g.modified, removed: g.removed };
    if (!g.conflicts.length && g.changed) {
      const text = renderGlossary(g.model);
      if (text !== glossary?.text) out.writes.push({ file: GLOSSARY_REL, text });
    }
  }
  for (const id of acceptBase) if (out.base[id]) {
    const owner = out.capabilities.find((c) => c._cur?.doc.blocks.some((b) => b.id === id));
    const blk = owner?._cur.doc.blocks.find((b) => b.id === id);
    if (blk) out.base[id] = blockHash(blk.livingText);
  }
  for (const c of out.capabilities) {
    if (!out.conflicts.length && c._changed) {
      if (c.deleted) out.writes.push({ file: c.file, text: null });
      else {
        const text = renderLiving(c._model);
        if (text !== c._cur?.text) out.writes.push({ file: c.file, text });
      }
    }
    delete c._model; delete c._changed; delete c._cur;
  }
  if (out.conflicts.length) out.writes = [];
  return out;
}
