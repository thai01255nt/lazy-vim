// Spec-layer markdown parsers (design v3 §2.3–§2.8, §6.6): living specs, deltas, glossary (living + delta),
// proposal, design; plus blockHash and the business-language lint. Pure and line-based like planningmd.mjs.
// Every parser returns `items` [{level, code, file, ref, line, message}] for problems local to the file.
import { createHash } from "node:crypto";
import { KIND_BY_WORD, KIND_BY_SECTION, KINDS, KEY_RE, CAP_RE, QUALITIES, SPECREF_RE, parseId } from "./specids.mjs";
import { MADR_REQUIRED } from "./speclint.mjs";

export const LIVING_SECTIONS = ["Purpose", "Requirements", "Rules", "Flows", "Retired IDs", "Change History"];
export const LIVING_HEADER = "<!-- audience: business · generated by hitl-index spec merge — edit through a change, not by hand -->";
export const REQ_MAX_CHARS = 500;
const DATE = "\\d{4}-\\d{2}-\\d{2}";
const RX = {
  title: /^# (.+)$/,
  metaCap: /^> capability: (\S+)/,
  metaKey: /\| key: (\S+)/,
  metaUpdated: new RegExp(`\\| updated: (${DATE})\\b`),
  metaChange: /\| change: (\S+)/,
  section: /^## (.+?)\s*$/,
  deltaSection: /^(ADDED|MODIFIED|REMOVED|RENAMED) (Requirements|Rules|Flows|Terms)$/,
  block: /^### (Requirement|Rule|Flow): (\S+)(?: +(.+))?$/,
  anyH3: /^### /,
  scenario: /^#### Scenario: (\S+)(?: +(.+))?$/,
  anyH4: /^#### /,
  step: /^- (GIVEN|WHEN|THEN|AND|BUT) (.+)$/,
  bullet: /^- /,
  quality: /^Quality: ?(.*)$/,
  fit: /^Fit(?: criterion)?: ?(.*)$/,
  rules: /^Rules: ?(.*)$/,
  changed: /^Changed: ?(.*)$/,
  reason: /^Reason: ?(.*)$/,
  keyword: /\b(SHALL|MUST|SHOULD|MAY)\b/g,
  term: /^### Term: (.+?)\s*$/,
  fence: /^\s*(```|~~~)/,
  clar: /\[NEEDS CLARIFICATION\b[^\]]*\]/g,
};
const MIGRATED = /<!--\s*migrated\s*-->/;
const PRIORITY = { SHALL: "must", MUST: "must", SHOULD: "should", MAY: "could" };

// ---------------------------------------------------------------- line helpers
/** Split into lines with markdown context: {n (1-based), raw, text (inline comments removed, trimEnd), fenced, comment}.
 *  `comment` = the line is only (part of) an HTML comment; `fenced` = inside a ``` / ~~~ block (fence lines included). */
export function scanLines(text) {
  const out = [];
  let fence = null; let inComment = false;
  String(text ?? "").split(/\r?\n/).forEach((raw, i) => {
    const n = i + 1;
    if (fence) {
      if (raw.trim().startsWith(fence)) fence = null;
      out.push({ n, raw, text: raw.replace(/\s+$/, ""), fenced: true, comment: false });
      return;
    }
    const fm = raw.match(RX.fence);
    if (fm && !inComment) { fence = fm[1]; out.push({ n, raw, text: raw.replace(/\s+$/, ""), fenced: true, comment: false }); return; }
    let s = raw; let t = "";
    let wasComment = inComment;
    while (s.length) {
      if (inComment) {
        const e = s.indexOf("-->");
        if (e < 0) { s = ""; break; }
        s = s.slice(e + 3); inComment = false;
      } else {
        const b = s.indexOf("<!--");
        if (b < 0) { t += s; s = ""; break; }
        t += s.slice(0, b); s = s.slice(b + 4); inComment = true; wasComment = true;
      }
    }
    t = t.replace(/\s+$/, "");
    out.push({ n, raw, text: t, fenced: false, comment: wasComment && t.trim() === "" });
  });
  return out;
}

const item = (items, file) => (level, code, ref, line, message) => items.push({ level, code, file: file ?? null, ref: ref ?? null, line: line ?? null, message });
const trimBlank = (lines) => {
  let a = 0, b = lines.length;
  while (a < b && lines[a].trim() === "") a++;
  while (b > a && lines[b - 1].trim() === "") b--;
  return lines.slice(a, b);
};
/** Collapse runs of blank lines to one. */
const collapseBlank = (lines) => lines.filter((l, i) => !(l.trim() === "" && i > 0 && lines[i - 1].trim() === ""));
const casefold = (s) => String(s ?? "").trim().toLocaleLowerCase();
export const termKey = casefold;

/** sha256 of a block: trailing whitespace stripped, blank-line runs collapsed, outer blank lines dropped (§7.4). */
export function normalizeBlock(text) {
  return collapseBlank(trimBlank(String(text ?? "").split(/\r?\n/).map((l) => l.replace(/\s+$/, "")))).join("\n");
}
export const blockHash = (text) => "sha256:" + createHash("sha256").update(normalizeBlock(text)).digest("hex");

/** `[NEEDS CLARIFICATION: …]` markers outside fences/comments: [{line, text}]. */
export function findClarifications(text) {
  const out = [];
  for (const L of scanLines(text)) {
    if (L.fenced) continue;
    for (const m of L.text.matchAll(RX.clar)) out.push({ line: L.n, text: m[0] });
  }
  return out;
}

const cells = (line) => line.replace(/^\s*\|/, "").replace(/\|\s*$/, "").split("|").map((c) => c.trim());
const isSep = (c) => c.every((x) => /^:?-+:?$/.test(x));

/** Parse a markdown table from lines: {header:[lower-cased names], rows:[{cells, line}]}. */
function parseTable(lines) {
  let header = null; const rows = [];
  for (const L of lines) {
    if (L.fenced || !/^\s*\|/.test(L.text)) continue;
    const c = cells(L.text);
    if (isSep(c)) continue;
    if (!header) { header = c.map((x) => x.toLowerCase()); continue; }
    rows.push({ cells: c, line: L.n });
  }
  return { header: header || [], rows };
}

// ---------------------------------------------------------------- living specs + deltas
function newBlock(kind, id, title, op, line) {
  return { kind, id, title: title ?? null, op, line, lines: [], statementLines: [], quality: null, qualitySub: null, fit: null, rules: [], scenarios: [],
    changed: null, reason: null, migrated: false };
}

/** Finish a block: text, livingText, statement, keywords, priority. */
function finishBlock(b) {
  const lines = trimBlank(b.lines.map((x) => x.raw.replace(/\s+$/, "")));
  b.text = lines.join("\n");
  // living form: comments removed, Changed:/Reason: lines dropped (they go to history / retired)
  const keep = b.lines.filter((x) => !x.comment && !(x.meta === "changed" || x.meta === "reason")).map((x) => (x.fenced ? x.raw.replace(/\s+$/, "") : x.text));
  b.livingText = collapseBlank(trimBlank(keep)).join("\n");
  b.statement = b.statementLines.join(" ").replace(/\s+/g, " ").trim();
  b.keywords = [...new Set([...b.statement.matchAll(RX.keyword)].map((m) => m[1]))];
  b.priority = b.keywords.length ? PRIORITY[b.keywords[0]] : null;
  delete b.lines; delete b.statementLines;
  return b;
}

/**
 * parseSpecMd(text, file, {mode:"living"|"delta"}) -> doc.
 * doc: {file, mode, title, capability, key, updated, change, hasMeta, purpose, hasPurpose, blocks[], retired[], history[],
 *       migratedRetired, items[]}. Delta blocks carry `op` (ADDED|MODIFIED|REMOVED); living blocks `op: null`.
 */
export function parseSpecMd(text, file, { mode = "living" } = {}) {
  const doc = { file, mode, title: null, capability: null, key: null, updated: null, change: null, hasMeta: false,
    purpose: null, hasPurpose: false, blocks: [], retired: [], history: [], migratedRetired: false, sections: [], items: [] };
  const add = item(doc.items, file);
  const delta = mode === "delta";
  let section = null; // {name, op, kind}
  let block = null; let scn = null; let purpose = null;
  const close = () => { if (block) doc.blocks.push(finishBlock(block)); block = null; scn = null; };
  for (const L of scanLines(text)) {
    const t = L.text;
    let m;
    if (!L.fenced && doc.title === null && (m = t.match(RX.title))) {
      doc.title = delta ? m[1].replace(/^Delta:\s*/, "").trim() : m[1].trim();
      continue;
    }
    if (!L.fenced && !doc.hasMeta && (m = t.match(RX.metaCap))) {
      doc.hasMeta = true;
      doc.capability = m[1];
      const k = t.match(RX.metaKey); doc.key = k ? k[1] : null;
      doc.updated = t.match(RX.metaUpdated)?.[1] ?? null;
      doc.change = t.match(RX.metaChange)?.[1] ?? null;
      if (!CAP_RE.test(doc.capability)) add("error", "SPEC_PARSE", doc.capability, L.n, `invalid capability name "${doc.capability}" (lower-case words joined by "-")`);
      if (!doc.key) add("error", "CAP_KEY_MISSING", doc.capability, L.n, `meta line has no "| key: <KEY>"`);
      else if (!KEY_RE.test(doc.key)) { add("error", "CAP_KEY_MISSING", doc.capability, L.n, `invalid capability key "${doc.key}" (2–6 upper-case letters/digits)`); doc.key = null; }
      continue;
    }
    if (!L.fenced && (m = t.match(RX.section))) {
      close();
      purpose = null;
      const name = m[1].trim();
      doc.sections.push(name);
      const dm = name.match(RX.deltaSection);
      if (name === "Purpose") { section = { name }; doc.hasPurpose = true; purpose = []; doc.purposeLine = L.n; }
      else if (!delta && LIVING_SECTIONS.includes(name)) section = { name, kind: KIND_BY_SECTION[name] || null, op: null };
      else if (delta && dm && dm[1] === "RENAMED") { section = { name, skip: true }; add("error", "DELTA_RENAMED_UNSUPPORTED", null, L.n, `## ${name}: RENAMED is not supported — ids are identity; change the title through MODIFIED`); }
      else if (delta && dm && dm[2] !== "Terms") section = { name, kind: KIND_BY_SECTION[dm[2]], op: dm[1] };
      else if (delta && name === "Retired IDs") { section = { name, kind: null, op: null }; if (MIGRATED.test(L.raw)) doc.migratedRetired = true; }
      else {
        section = { name, skip: true };
        add(delta ? "warn" : "error", "SPEC_UNKNOWN_SECTION", null, L.n, delta ? `unknown section "## ${name}" is ignored by merge`
          : `unknown section "## ${name}" in a living spec (allowed: ${LIVING_SECTIONS.join(", ")})`);
      }
      continue;
    }
    if (!section) continue;
    if (section.name === "Purpose") {
      if (purpose && !L.comment) purpose.push(L.fenced ? L.raw : t);
      doc.purpose = trimBlank(purpose || []).join("\n") || null;
      continue;
    }
    if (section.name === "Retired IDs") {
      if (MIGRATED.test(L.raw)) doc.migratedRetired = true;
      if (!L.fenced && (m = t.match(/^- (\S+)(?: (.*))?$/))) {
        const title = (m[2] || "").split(/ — | -- /)[0].trim();
        doc.retired.push({ id: m[1], title, line: L.n, raw: t });
        if (!parseId(m[1])) add("error", "ID_BAD_FORMAT", m[1], L.n, `retired id "${m[1]}" is not a spec id`);
      }
      continue;
    }
    if (section.name === "Change History") { if (!L.fenced && t.startsWith("- ")) doc.history.push(t); continue; }
    if (section.skip) continue;
    // Requirements / Rules / Flows (living) or <OP> <Kind> (delta)
    if (!L.fenced && RX.anyH3.test(t)) {
      close();
      m = t.match(RX.block);
      if (!m) { add("error", "SPEC_PARSE", null, L.n, `malformed block header "${t}" (### Requirement|Rule|Flow: <ID> <title>)`); continue; }
      const kind = KIND_BY_WORD[m[1]]; const id = m[2]; const pid = parseId(id);
      if (kind !== section.kind) add("error", "SPEC_PARSE", id, L.n, `### ${m[1]} inside ## ${section.name}`);
      if (!pid || pid.kind === "S" || KINDS[kind].idKind !== pid.kind) { add("error", "ID_BAD_FORMAT", id, L.n, `"${id}" is not a ${m[1].toLowerCase()} id (<KEY>-${KINDS[kind].idKind}<n>)`); continue; }
      if (doc.key && pid.key !== doc.key) add("error", "ID_KEY_MISMATCH", id, L.n, `${id} does not use the capability key ${doc.key}`);
      if (!m[3] && section.op !== "REMOVED") add("error", "SPEC_PARSE", id, L.n, `${id} has no title`);
      block = newBlock(kind, id, m[3]?.trim() ?? null, section.op ?? null, L.n);
      block.migrated = MIGRATED.test(L.raw);
      block.lines.push(L);
      continue;
    }
    if (!block) {
      if (!L.fenced && t.trim() && !L.comment) add("warn", "SPEC_PARSE", null, L.n, `text outside a block in ## ${section.name} is ignored`);
      continue;
    }
    if (MIGRATED.test(L.raw)) block.migrated = true;
    if (!L.fenced && (m = t.match(RX.changed))) { L.meta = "changed"; block.changed = m[1].trim() || null; block.lines.push(L); continue; }
    if (!L.fenced && (m = t.match(RX.reason))) { L.meta = "reason"; block.reason = m[1].trim() || null; block.lines.push(L); continue; }
    block.lines.push(L);
    if (block.kind !== "requirement" || L.fenced) continue;
    if (RX.anyH4.test(t)) {
      m = t.match(RX.scenario);
      if (!m) { add("error", "SPEC_PARSE", block.id, L.n, `malformed scenario header "${t}" (#### Scenario: <REQ-ID>.S<k> <title>)`); scn = null; continue; }
      const pid = parseId(m[1]);
      if (!pid || pid.kind !== "S") add("error", "ID_BAD_FORMAT", m[1], L.n, `"${m[1]}" is not a scenario id (<REQ-ID>.S<k>)`);
      else if (pid.req !== block.id) add("error", "SCN_ID_MISMATCH", m[1], L.n, `scenario ${m[1]} is inside ${block.id}`);
      if (!m[2]) add("error", "SPEC_PARSE", m[1], L.n, `scenario ${m[1]} has no title`);
      scn = { id: m[1], title: m[2]?.trim() ?? null, line: L.n, steps: [] };
      block.scenarios.push(scn);
      continue;
    }
    if (!scn) {
      if ((m = t.match(RX.quality))) {
        L.meta = "quality";
        // ISO/IEC 25010:2023 characteristic, optionally with a sub-characteristic: "performance-efficiency (time behaviour)"
        const q = m[1].trim().match(/^([a-z-]+)(?:\s*(?:\(([^)]*)\)|\/\s*(.+)))?$/);
        if (q && QUALITIES.includes(q[1])) { block.quality = q[1]; block.qualitySub = (q[2] || q[3] || "").trim() || null; }
        else add("error", "SPEC_PARSE", block.id, L.n, `invalid Quality "${m[1].trim()}" (ISO 25010: ${QUALITIES.join("|")})`);
      } else if ((m = t.match(RX.fit))) {
        L.meta = "fit";
        block.fit = m[1].trim() || null;
      } else if ((m = t.match(RX.rules))) {
        L.meta = "rules";
        for (const r of m[1].split(",").map((s) => s.trim()).filter(Boolean)) {
          if (parseId(r)?.kind === "BR") block.rules.push(r);
          else add("error", "SPEC_PARSE", block.id, L.n, `Rules: "${r}" is not a rule id (<KEY>-BR<n>)`);
        }
      } else if (!L.comment && t.trim() && !/^\s*\|/.test(t)) block.statementLines.push(t.trim());
      continue;
    }
    if ((m = t.match(RX.step))) scn.steps.push({ kw: m[1], text: m[2].trim() });
    else if (/^\s+\S/.test(t) && scn.steps.length) scn.steps.at(-1).text += " " + t.trim();
    else if (RX.bullet.test(t)) add("error", "SPEC_PARSE", scn.id, L.n, `scenario step must start with GIVEN|WHEN|THEN|AND|BUT: "${t}"`);
  }
  close();
  if (doc.title === null) add("error", "SPEC_PARSE", null, 1, "missing # title");
  if (!doc.hasMeta) add("error", "CAP_KEY_MISSING", null, null, `missing meta line "> capability: <name> | key: <KEY>${delta ? " | change: <id>" : ""}"`);
  else if (delta && !doc.change) add("error", "SPEC_PARSE", doc.capability, null, `delta meta line has no "| change: <id>"`);
  if (doc.retired.length && delta && !doc.migratedRetired) add("error", "SPEC_UNKNOWN_SECTION", null, null, "## Retired IDs is allowed in a delta only when written by migration (<!-- migrated -->)");
  checkBlocks(doc, add);
  return doc;
}

function checkBlocks(doc, add) {
  const delta = doc.mode === "delta";
  const seen = new Map(); // id -> op ("" in living)
  const scnSeen = new Set();
  for (const b of doc.blocks) {
    const op = b.op || "";
    if (seen.has(b.id)) {
      if (delta && seen.get(b.id) !== op) add("error", "DELTA_CONFLICT", b.id, b.line, `${b.id} appears in both ${seen.get(b.id)} and ${op}`);
      else add("error", "ID_DUP", b.id, b.line, `duplicate id ${b.id}`);
    } else seen.set(b.id, op);
    for (const s of b.scenarios) {
      if (scnSeen.has(s.id)) add("error", "ID_DUP", s.id, s.line, `duplicate scenario id ${s.id}`);
      scnSeen.add(s.id);
      if (doc.key && parseId(s.id) && parseId(s.id).key !== doc.key) add("error", "ID_KEY_MISMATCH", s.id, s.line, `${s.id} does not use the capability key ${doc.key}`);
      if (b.op === "REMOVED") continue;
      const kws = new Set(s.steps.map((x) => x.kw));
      if (!kws.has("WHEN") || !kws.has("THEN")) add("error", "SCN_NO_WHEN_THEN", s.id, s.line, `${s.id} needs at least one "- WHEN" and one "- THEN" step`);
    }
    if (b.op === "REMOVED") {
      if (!b.reason) add("error", "REMOVED_NO_REASON", b.id, b.line, `REMOVED ${b.id} needs a "Reason: …" line`);
      continue;
    }
    if (b.op === "MODIFIED" && !b.changed) add("error", "MODIFIED_NO_CHANGED_LINE", b.id, b.line, `MODIFIED ${b.id} needs a one-line "Changed: …"`);
    if (b.kind !== "requirement") continue;
    if (!b.keywords.length) add("error", "REQ_NO_KEYWORD", b.id, b.line, `${b.id} statement has no SHALL/MUST/SHOULD/MAY`);
    if (b.keywords.length > 1) add("warn", "REQ_MULTI_KEYWORD", b.id, b.line, `${b.id} statement mixes ${b.keywords.join("/")} (priority taken from ${b.keywords[0]})`);
    if (b.statement.length > REQ_MAX_CHARS) add("warn", "REQ_TOO_LONG", b.id, b.line, `${b.id} statement is ${b.statement.length} chars (> ${REQ_MAX_CHARS}); consider splitting`);
    if (!b.scenarios.length) {
      const level = !delta || b.migrated ? "warn" : "error";
      add(level, "REQ_NO_SCENARIO", b.id, b.line, `${b.id} has no #### Scenario`);
    }
  }
  if (!delta) for (const r of doc.retired) if (seen.has(r.id)) add("error", "ID_DUP", r.id, r.line, `${r.id} is both retired and live`);
}

export const parseLivingSpec = (text, file) => parseSpecMd(text, file, { mode: "living" });
export const parseDelta = (text, file) => parseSpecMd(text, file, { mode: "delta" });

/** Ids a spec doc uses, by kind letter: {R:Set<n>, BR:Set<n>, UC:Set<n>, S: Map<reqId, Set<k>>} (blocks + scenarios + retired). */
export function usedIds(doc, into = { R: new Set(), BR: new Set(), UC: new Set(), S: new Map() }) {
  const addId = (id) => {
    const p = parseId(id); if (!p) return;
    if (p.kind === "S") { if (!into.S.has(p.req)) into.S.set(p.req, new Set()); into.S.get(p.req).add(p.k); }
    else into[p.kind].add(p.n);
  };
  for (const b of doc?.blocks || []) { addId(b.id); for (const s of b.scenarios) addId(s.id); }
  for (const r of doc?.retired || []) addId(r.id);
  return into;
}

// ---------------------------------------------------------------- glossary
/** parseGlossary(text, file, {delta}) -> {file, mode, title, updated, terms:[{term, key, op, line, text, avoid}], items}. */
export function parseGlossary(text, file, { delta = false } = {}) {
  const doc = { file, mode: delta ? "delta" : "living", title: null, updated: null, terms: [], items: [] };
  const add = item(doc.items, file);
  let op = null; let cur = null; let inSection = !delta;
  const close = () => {
    if (!cur) return;
    const keep = cur.lines.filter((x) => !x.comment && x.meta !== "reason" && x.meta !== "changed").map((x) => (x.fenced ? x.raw.replace(/\s+$/, "") : x.text));
    cur.text = collapseBlank(trimBlank(keep)).join("\n");
    delete cur.lines;
    doc.terms.push(cur); cur = null;
  };
  for (const L of scanLines(text)) {
    const t = L.text; let m;
    if (!L.fenced && doc.title === null && (m = t.match(RX.title))) { doc.title = m[1].trim(); continue; }
    if (!L.fenced && !doc.updated && (m = t.match(new RegExp(`^> .*updated: (${DATE})`)))) { doc.updated = m[1]; continue; }
    if (!L.fenced && (m = t.match(RX.section))) {
      close();
      const dm = m[1].trim().match(RX.deltaSection);
      if (delta && dm && dm[2] === "Terms" && dm[1] !== "RENAMED") { op = dm[1]; inSection = true; }
      else if (delta && dm && dm[1] === "RENAMED") { inSection = false; add("error", "DELTA_RENAMED_UNSUPPORTED", null, L.n, "RENAMED Terms is not supported: REMOVED the old term and ADDED the new one"); }
      else { inSection = false; add(delta ? "warn" : "error", "SPEC_UNKNOWN_SECTION", null, L.n, `unknown section "## ${m[1].trim()}" in ${delta ? "a glossary delta" : "GLOSSARY.md"}`); }
      continue;
    }
    if (!inSection) continue;
    if (!L.fenced && RX.anyH3.test(t)) {
      close();
      if (!(m = t.match(RX.term))) { add("error", "SPEC_PARSE", null, L.n, `malformed term header "${t}" (### Term: <term>)`); continue; }
      cur = { term: m[1], key: casefold(m[1]), op: delta ? op : null, line: L.n, lines: [L], avoid: [], reason: null };
      continue;
    }
    if (!cur) continue;
    if (!L.fenced && (m = t.match(/^_Avoid_: ?(.*)$/))) cur.avoid = m[1].split(",").map((s) => s.trim()).filter(Boolean);
    if (!L.fenced && (m = t.match(RX.reason))) { L.meta = "reason"; cur.reason = m[1].trim() || null; }
    if (!L.fenced && t.match(RX.changed)) L.meta = "changed";
    cur.lines.push(L);
  }
  close();
  const seen = new Map();
  for (const x of doc.terms) {
    if (seen.has(x.key)) add("error", delta && seen.get(x.key) !== x.op ? "DELTA_CONFLICT" : "ID_DUP", x.term, x.line, `term "${x.term}" appears twice`);
    else seen.set(x.key, x.op);
  }
  return doc;
}

