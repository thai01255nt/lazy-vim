export const PROPOSAL_REQUIRED = ["Why", "What changes", "Capabilities", "Artifacts"];

function sectionsOf(lines) {
  const out = new Map(); let cur = null;
  for (const L of lines) {
    const m = !L.fenced && L.text.match(RX.section);
    if (m) { cur = { name: m[1].trim(), line: L.n, lines: [] }; if (!out.has(cur.name)) out.set(cur.name, cur); continue; }
    if (cur) cur.lines.push(L);
  }
  return out;
}
const sectionText = (s) => (s ? trimBlank(s.lines.filter((L) => !L.comment).map((L) => (L.fenced ? L.raw : L.text))).join("\n") : null);

/** parseProposal(text, file) -> {title, change, status, created, updated, sections{name:text}, capabilities[], noBehaviourChange,
 *  artifacts[], deferred[], clarifications[], items}. */
export function parseProposal(text, file) {
  const doc = { file, title: null, change: null, status: null, created: null, updated: null, sections: {}, capabilities: [],
    noBehaviourChange: false, artifacts: [], deferred: [], clarifications: findClarifications(text), items: [] };
  const add = item(doc.items, file);
  const lines = scanLines(text);
  for (const L of lines) {
    if (L.fenced) continue;
    let m;
    if (doc.title === null && (m = L.text.match(RX.title))) doc.title = m[1].trim();
    else if (!doc.change && (m = L.text.match(/^> change: (\S+)/))) {
      doc.change = m[1];
      doc.status = L.text.match(/\| status: (draft|approved)\b/)?.[1] ?? null;
      doc.created = L.text.match(new RegExp(`\\| created: (${DATE})`))?.[1] ?? null;
      doc.updated = L.text.match(new RegExp(`\\| updated: (${DATE})`))?.[1] ?? null;
      if (!doc.status) add("error", "SPEC_PARSE", doc.change, L.n, `proposal meta needs "| status: draft|approved"`);
    }
  }
  if (!doc.title) add("error", "SPEC_PARSE", null, 1, "proposal has no # title");
  if (!doc.change) add("error", "SPEC_PARSE", null, null, `proposal has no meta line "> change: <id> | status: draft|approved"`);
  const secs = sectionsOf(lines);
  for (const [name, s] of secs) doc.sections[name] = sectionText(s);
  for (const name of PROPOSAL_REQUIRED) if (!secs.has(name)) add("error", "PROPOSAL_SECTION_MISSING", name, null, `proposal has no "## ${name}" section`);
  const cap = secs.get("Capabilities");
  if (cap) {
    doc.noBehaviourChange = /none \(no behaviour change\)/i.test(sectionText(cap) || "");
    const tb = parseTable(cap.lines);
    const col = (n) => tb.header.indexOf(n);
    for (const r of tb.rows) {
      const get = (n) => (col(n) >= 0 ? r.cells[col(n)] ?? "" : "");
      const c = get("capability");
      if (!c || /^none\b/i.test(c)) continue;
      doc.capabilities.push({ capability: c, key: get("key") || null, change: get("change").toLowerCase() || null, requirements: get("requirements"), line: r.line });
    }
  }
  const art = secs.get("Artifacts");
  if (art) {
    const tb = parseTable(art.lines);
    const col = (n) => tb.header.indexOf(n);
    for (const r of tb.rows) {
      const get = (n) => (col(n) >= 0 ? r.cells[col(n)] ?? "" : "");
      doc.artifacts.push({ artifact: get("artifact").toLowerCase(), decision: get("decision").toLowerCase(), why: get("why"), line: r.line });
    }
  }
  const def = secs.get("Deferred");
  if (def) for (const L of def.lines) if (!L.fenced && /^- \S/.test(L.text)) doc.deferred.push(L.text.slice(2).trim());
  doc.coverage = parseCoverage(secs.get("Coverage"));
  const oq = secs.get("Open questions");
  doc.forced = oq ? oq.lines.filter((L) => !L.fenced && /💡 Forced:/.test(L.text)).map((L) => L.text.replace(/^[-*]\s*(\[[ x]\]\s*)?/, "").trim()) : [];
  return doc;
}

/** Coverage status symbols of the plan interview (shared/interview.md §3). */
export const COVERAGE_STATUS = { "✅": "clear", "⚠️": "partial", "⚠": "partial", "❌": "missing", "—": "n/a", "-": "n/a" };

/** `## Coverage` table `| category | status | note |` → [{category, status: clear|partial|missing|n/a|null, note, line}] or null. */
function parseCoverage(sec) {
  if (!sec) return null;
  const tb = parseTable(sec.lines);
  const col = (n) => tb.header.indexOf(n);
  return tb.rows.map((r) => {
    const get = (n) => (col(n) >= 0 ? r.cells[col(n)] ?? "" : "");
    const raw = get("status").trim();
    const sym = Object.keys(COVERAGE_STATUS).find((k) => raw.startsWith(k));
    return { category: get("category"), status: sym ? COVERAGE_STATUS[sym] : null, note: get("note"), line: r.line };
  }).filter((c) => c.category);
}

/** Decision recorded for an artifact row ("design" → "skipped" | "included" | …), or null. */
export function artifactDecision(proposal, name) {
  const row = (proposal?.artifacts || []).find((a) => a.artifact === name);
  if (!row) return null;
  if (/skipped/.test(row.decision)) return "skipped";
  if (/included|assumed/.test(row.decision)) return "included";
  return row.decision || null;
}

// ---------------------------------------------------------------- design
const DCOLS = { id: "id", decision: "decision", why: "why", alternatives: "alternatives", "cost if wrong": "cost", serves: "serves", status: "status" };
/** parseDesign(text, file) -> {title, change, status, updated, decisions[], contracts[], sections{}, items}. */
export function parseDesign(text, file) {
  const doc = { file, title: null, change: null, status: null, updated: null, decisions: [], contracts: [], sections: {}, items: [] };
  const add = item(doc.items, file);
  const lines = scanLines(text);
  for (const L of lines) {
    if (L.fenced) continue;
    let m;
    if (doc.title === null && (m = L.text.match(RX.title))) doc.title = m[1].replace(/^Design:\s*/, "").trim();
    else if (!doc.change && (m = L.text.match(/^> change: (\S+)/))) {
      doc.change = m[1];
      doc.status = L.text.match(/\| status: (draft|approved)\b/)?.[1] ?? null;
      doc.updated = L.text.match(new RegExp(`\\| updated: (${DATE})`))?.[1] ?? null;
      if (!doc.status) add("error", "SPEC_PARSE", doc.change, L.n, `design meta needs "| status: draft|approved"`);
    }
  }
  if (!doc.change) add("error", "SPEC_PARSE", null, null, `design has no meta line "> change: <id> | status: draft|approved"`);
  const secs = sectionsOf(lines);
  for (const [name, s] of secs) doc.sections[name] = sectionText(s);
  const dec = secs.get("Decisions");
  doc.decisionDetails = [];
  if (dec) {
    let header = null; const seen = new Set();
    // the D table is the decision log index; `### D-n <title>` MADR detail blocks follow it (their tables are not D rows)
    const firstH3 = dec.lines.findIndex((L) => !L.fenced && /^### /.test(L.text));
    const tableLines = firstH3 < 0 ? dec.lines : dec.lines.slice(0, firstH3);
    if (firstH3 >= 0) doc.decisionDetails = parseDecisionDetails(dec.lines.slice(firstH3), add);
    for (const L of tableLines) {
      if (L.fenced || !/^\s*\|/.test(L.text)) continue;
      const c = cells(L.text);
      if (isSep(c)) continue;
      if (!header) {
        header = {};
        c.forEach((name, i) => { const k = DCOLS[name.toLowerCase()]; if (k && !(k in header)) header[k] = i; });
        if (!("id" in header)) { add("error", "SPEC_PARSE", null, L.n, "decision table has no id column"); header = { invalid: true }; }
        continue;
      }
      if (header.invalid) continue;
      const get = (k) => (k in header ? (c[header[k]] ?? "") : "");
      const id = get("id");
      if (!/^D-\d+$/.test(id)) { add("error", "SPEC_PARSE", id, L.n, `invalid decision id "${id}"`); continue; }
      if (seen.has(id)) { add("error", "ID_DUP", id, L.n, `duplicate decision id ${id}`); continue; }
      seen.add(id);
      const serves = [];
      for (const r of get("serves").split(",").map((s) => s.trim()).filter((s) => s && !["—", "-"].includes(s))) {
        if (SPECREF_RE.test(r) || /^R-\d+$/.test(r)) { if (!serves.includes(r)) serves.push(r); }
        else add("error", "DESIGN_SERVES_UNKNOWN", id, L.n, `${id}: serves item "${r}" is not a requirement or rule id`);
      }
      const raw = get("status");
      const sm = raw.match(DEC_STATUS_RE);
      if (!sm) add("error", "DESIGN_DEC_STATUS", id, L.n, `${id}: invalid status "${raw}" (${DEC_STATUSES})`);
      doc.decisions.push({ id, decision: get("decision"), why: get("why"), alternatives: get("alternatives"), cost: get("cost"), serves,
        status: sm ? (sm[2] ? "superseded" : sm[1]) : raw, supersededBy: sm?.[2] || null, line: L.n });
    }
  }
  // MADR consistency (warnings): supersede targets exist, detail blocks belong to a D row and carry the MADR core
  const ids = new Set(doc.decisions.map((d) => d.id));
  for (const d of doc.decisions) if (d.supersededBy && (!ids.has(d.supersededBy) || d.supersededBy === d.id))
    add("warn", "DESIGN_DEC_SUPERSEDE_UNKNOWN", d.id, d.line, `${d.id} is superseded by ${d.supersededBy}, which is not another row of the decision table`);
  for (const x of doc.decisionDetails) {
    if (!ids.has(x.id)) add("warn", "DESIGN_DEC_DETAIL_UNKNOWN", x.id, x.line, `### ${x.id} has no row in the decision table`);
    const missing = MADR_REQUIRED.filter((k) => !x.fields.has(k));
    if (missing.length) add("warn", "DESIGN_DEC_INCOMPLETE", x.id, x.line, `${x.id} MADR block misses: ${missing.join(", ")}`);
  }
  const con = secs.get("Contracts");
  if (con) for (const L of con.lines) {
    const m = !L.fenced && L.text.match(/^- (contracts\/\S+)(?:\s+(?:—|–|--|-)\s+(.*))?$/);
    if (m) doc.contracts.push({ file: m[1], boundary: m[2]?.trim() ?? null, line: L.n });
  }
  return doc;
}

/** Decision statuses: MADR 4 (proposed, accepted, rejected, deprecated, superseded by …) with hitl D-n ids. */
export const DEC_STATUS_RE = /^(proposed|accepted|rejected|deprecated|superseded by (D-\d+))$/;
const DEC_STATUSES = "proposed|accepted|rejected|deprecated|superseded by D-n";
const MADR_LABEL = /^\s*(?:[-*]\s*)?\*\*([^*]+?)\s*:?\*\*\s*:?/;
const MADR_ALIASES = { "context": "context and problem", "context and problem statement": "context and problem", "problem": "context and problem",
  "options": "considered options", "outcome": "decision outcome", "decision": "decision outcome" };
/** `### D-n <title>` blocks with `**Label**:` lines → [{id, title, line, fields:Set<lower-case label>}]. */
function parseDecisionDetails(lines, add) {
  const out = []; let cur = null;
  for (const L of lines) {
    if (L.fenced) continue;
    const h = L.text.match(/^### (\S+)(?:\s+(.*))?$/);
    if (h) {
      if (!/^D-\d+$/.test(h[1])) { add("warn", "DESIGN_DEC_DETAIL_UNKNOWN", h[1], L.n, `"### ${h[1]}" under ## Decisions is not a decision id (### D-n <title>)`); cur = null; continue; }
      cur = { id: h[1], title: (h[2] || "").trim() || null, line: L.n, fields: new Set() }; out.push(cur); continue;
    }
    const m = cur && L.text.match(MADR_LABEL);
    if (m) { const k = m[1].trim().toLowerCase(); cur.fields.add(MADR_ALIASES[k] || k); }
  }
  return out;
}

// ---------------------------------------------------------------- business-language lint (§6.6)
const BIZ_RULES = [
  ["backtick", /`[^`]+`/g],
  ["call", /\b\w+\(\)/g],
  ["camelCase", /\b[a-z]+[A-Z]\w*\b|\b[A-Z][a-z]+[A-Z]\w*\b/g],
  ["snake_case", /\b[a-z]+_[a-z_]+\b/g],
  ["path", /\b[\w.-]+\/[\w./-]+\.\w{1,5}\b/g],
  ["http", /\b(GET|POST|PUT|PATCH|DELETE) \//g],
];
/** bizLint(text, {terms}) -> [{line, token, rule}]. Skips fences, comments, the meta line, and tables inside `### Rule:` blocks.
 *  `terms`: glossary terms (any case) that are always allowed. */
export function bizLint(text, { terms = [] } = {}) {
  const allowed = new Set([...terms].map(casefold));
  const out = []; let inRule = false;
  for (const L of scanLines(text)) {
    if (L.fenced || L.comment) continue;
    const t = L.text;
    if (/^#{1,3} /.test(t)) inRule = /^### Rule: /.test(t);
    if (/^> /.test(t)) continue;
    if (inRule && /^\s*\|/.test(t)) continue;
    for (const [rule, rx] of BIZ_RULES) {
      for (const m of t.matchAll(rx)) {
        const tok = m[0];
        if (allowed.has(casefold(tok.replace(/^`|`$/g, "")))) continue;
        out.push({ line: L.n, token: tok, rule });
      }
    }
  }
  return out;
}
